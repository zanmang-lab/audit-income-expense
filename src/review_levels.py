def kind_of(text: str, level: str | None = None) -> str:
    for kind, keys in KIND_RULES:
        if kind == "연체일수를 못 정함" and level == CHECK:
            continue  # 일수를 계산한 항목 안의 '…으로 받았다면 나누어떨어지지 않음' 같은 보조 설명은 제외
        if kind == "연체일수 계산":
            if "일 = 연체료" in text:
                return kind
            continue
        if any(k in text for k in keys):
            return kind
    return "기타"
